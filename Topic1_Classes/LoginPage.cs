namespace Topic1_Classes
{
    /// <summary>
    /// ПРАКТИЧЕСКИЙ ПРИМЕР: Page Object для демонстрации свойств (Properties)
    /// 
    /// Это пример из README раздела 6 — реальное использование:
    /// - Приватные поля (_username, _password) скрыты от внешнего кода
    /// - Публичные свойства (Username, IsLoggedIn) предоставляют управляемый доступ
    /// - Свойство Username имеет валидацию в set
    /// - Метод Login() демонстрирует как работает инкапсуляция
    /// 
    /// Это показывает ЗАЧЕМ нужны свойства:
    /// 1. Скрытие внутренних деталей (инкапсуляция)
    /// 2. Валидация данных при присваивании
    /// 3. Контроль доступа (read-only свойства)
    /// 4. Возможность изменить реализацию без изменения интерфейса
    /// </summary>
    public class LoginPage
    {
        // ============================================================
        // ПРИВАТНЫЕ ПОЛЯ — скрыты от внешнего кода
        // Это ВНУТРЕННИЕ детали реализации
        // ============================================================
        private string _username;
        private string _password;
        private bool _isLoggedIn;

        // ============================================================
        // ПУБЛИЧНЫЕ СВОЙСТВА — предоставляют управляемый доступ
        // Это то, что видит внешний код
        // ============================================================

        /// <summary>
        /// Свойство Username с ВАЛИДАЦИЕЙ
        /// Демонстрирует как использовать get и set для контроля доступа
        /// </summary>
        public string Username
        {
            get 
            { 
                return _username; 
            }
            set 
            { 
                // ВАЛИДАЦИЯ: проверяем значение перед присваиванием
                if (string.IsNullOrWhiteSpace(value))
                {
                    throw new ArgumentException("Username не может быть пустым!");
                }
                _username = value; 
            }
        }

        /// <summary>
        /// Свойство Password с ВАЛИДАЦИЕЙ
        /// Показывает минимальную длину пароля
        /// </summary>
        public string Password
        {
            get 
            { 
                return _password; 
            }
            set 
            { 
                // ВАЛИДАЦИЯ: пароль должен быть минимум 6 символов
                if (string.IsNullOrWhiteSpace(value) || value.Length < 6)
                {
                    throw new ArgumentException("Пароль должен быть минимум 6 символов!");
                }
                _password = value; 
            }
        }

        /// <summary>
        /// Свойство IsLoggedIn — ТОЛЬКО ДЛЯ ЧТЕНИЯ
        /// Внешний код не может изменить этот флаг напрямую
        /// Его можно изменить только через метод Login() или Logout()
        /// 
        /// Это демонстрирует ИНКАПСУЛЯЦИЮ:
        /// - Скрываем внутреннее состояние
        /// - Предоставляем методы для безопасного изменения состояния
        /// </summary>
        public bool IsLoggedIn 
        { 
            get { return _isLoggedIn; } 
        }

        // ============================================================
        // КОНСТРУКТОР
        // ============================================================

        /// <summary>
        /// Конструктор инициализирует объект в начальное состояние
        /// </summary>
        public LoginPage()
        {
            _username = "";
            _password = "";
            _isLoggedIn = false;
        }

        // ============================================================
        // МЕТОДЫ — контролируют работу с объектом
        // ============================================================

        /// <summary>
        /// Метод Login() демонстрирует как работает валидация
        /// и контролируемое изменение состояния
        /// </summary>
        public bool Login(string password)
        {
            // ВАЛИДАЦИЯ: проверяем заполненность Username
            if (string.IsNullOrEmpty(_username))
            {
                throw new ArgumentException("Username не может быть пустой!");
            }

            // ВАЛИДАЦИЯ: проверяем пароль
            if (string.IsNullOrEmpty(password) || password.Length < 6)
            {
                throw new ArgumentException("Пароль некорректен!");
            }

            // Если валидация прошла, сохраняем пароль и устанавливаем флаг
            _password = password;
            _isLoggedIn = true;
            return true;
        }

        /// <summary>
        /// Метод Logout() — единственный способ изменить IsLoggedIn на false
        /// Это демонстрирует инкапсуляцию: контролируем доступ к внутреннему состоянию
        /// </summary>
        public void Logout()
        {
            _isLoggedIn = false;
            _password = "";  // Очищаем пароль при выходе
        }

        /// <summary>
        /// Метод GetInfo() показывает как использовать свойства в методах
        /// </summary>
        public string GetInfo()
        {
            return $"User: {Username}, Logged in: {IsLoggedIn}";
        }
    }
}
